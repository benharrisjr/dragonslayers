#!/usr/bin/env bash
# Build the game for desktop/mobile and upload to Google Drive.
# The game's names come from project.env.
#
# FIRST-TIME SETUP:
#   brew install rclone
#   rclone config   # add a remote named "gdrive" pointing to Google Drive
#   Download Godot export templates via Editor > Export > Manage Export Templates
#   sudo xcode-select -s /Applications/Xcode.app/Contents/Developer
#
# USAGE:
#   ./build.sh [options] [platforms...]
#
#   Platforms: mac  windows  linux-x64  linux-arm64  ios  (default: all)
#
# OPTIONS:
#   --skip-upload        build only, don't upload
#   --version VERSION    override version tag (default: git describe)
#   --gdrive-remote NAME rclone remote name (default: gdrive)
#   --gdrive-folder PATH folder inside remote (default: GDRIVE_FOLDER_DEFAULT in project.env)
#   --steam full|demo    also export + upload desktop builds to Steam via
#                        steam/steam_upload.sh (never sets the build live)
#   --upx                UPX-compress the Windows and Linux executables before
#                        zipping (needs upx: arm64 `brew install upx`).
#                        macOS is skipped: UPX breaks codesigning/notarization.
#
# ENV VARS:
#   GODOT              path to Godot binary (auto-detected if not set)
#   IOS_TEAM_ID        Apple Developer Team ID (required for iOS)
#   ASC_API_KEY_ID     App Store Connect API key ID (for upload)
#   ASC_ISSUER_ID      App Store Connect issuer ID (for upload)
#   ASC_APPLE_ID       Apple ID email (alternative to API key)
#   ASC_APP_PASSWORD   App-specific password (alternative to API key)
#   STEAM_BUILDER_USER Steam account for --steam uploads (see steam/README.md)

set -euo pipefail

# ── Configuration ─────────────────────────────────────────────────────────────

PROJECT_DIR="$(cd "$(dirname "$0")" && pwd)"
# shellcheck disable=SC1091
source "$PROJECT_DIR/project.env"
BUILD_DIR="$PROJECT_DIR/builds"
DIST_DIR="$PROJECT_DIR/dist"
XCODE_DEVELOPER_DIR="/Applications/Xcode.app/Contents/Developer"

GDRIVE_REMOTE="${GDRIVE_REMOTE:-gdrive}"
GDRIVE_FOLDER="${GDRIVE_FOLDER:-$GDRIVE_FOLDER_DEFAULT}"

# ── Argument parsing ───────────────────────────────────────────────────────────

PLATFORMS=()
SKIP_UPLOAD=false
VERSION=""
STEAM_APP=""
USE_UPX=false

while [[ $# -gt 0 ]]; do
    case $1 in
        --skip-upload)   SKIP_UPLOAD=true ;;
        --version)       VERSION="$2"; shift ;;
        --gdrive-remote) GDRIVE_REMOTE="$2"; shift ;;
        --gdrive-folder) GDRIVE_FOLDER="$2"; shift ;;
        --steam)         STEAM_APP="$2"; shift ;;
        --upx)           USE_UPX=true ;;
        mac|windows|linux-x64|linux-arm64|ios|all) PLATFORMS+=("$1") ;;
        -h|--help)
            sed -n '2,31p' "$0" | sed 's/^# \?//'
            exit 0
            ;;
        *) echo "Unknown argument: $1" >&2; exit 1 ;;
    esac
    shift
done

[[ ${#PLATFORMS[@]} -eq 0 ]] && PLATFORMS=("all")

should_build() { [[ " ${PLATFORMS[*]} " =~ " all " ]] || [[ " ${PLATFORMS[*]} " =~ " $1 " ]]; }

# ── Resolve version ────────────────────────────────────────────────────────────

if [[ -z "$VERSION" ]]; then
    VERSION=$(git -C "$PROJECT_DIR" describe --tags --always 2>/dev/null || date +%Y%m%d-%H%M%S)
fi
echo "Version: $VERSION"

# The exported game reads its version from here (FeedbackReporter.version, for
# bug reports). Gitignored; removed again when the build finishes.
BUILD_INFO="$PROJECT_DIR/build_info.gd"
printf '## Generated by build.sh, do not edit or commit.\nconst VERSION := "%s"\n' "$VERSION" > "$BUILD_INFO"
trap 'rm -f "$BUILD_INFO" "$BUILD_INFO.uid"' EXIT

# ── Locate Godot ──────────────────────────────────────────────────────────────

find_godot() {
    if [[ -n "${GODOT:-}" ]]; then
        echo "$GODOT"; return
    fi
    for bin in godot godot4 Godot godot-4; do
        if command -v "$bin" &>/dev/null; then
            echo "$bin"; return
        fi
    done
    local app
    for app in "/Applications/Godot.app/Contents/MacOS/Godot" "$HOME/Applications/Godot.app/Contents/MacOS/Godot"; do
        if [[ -f "$app" ]]; then
            echo "$app"; return
        fi
    done
    echo "ERROR: Godot binary not found. Set the GODOT env var or add it to PATH." >&2
    exit 1
}

GODOT=$(find_godot)
echo "Godot: $GODOT"

if $USE_UPX; then
    UPX=$(command -v upx || ls /opt/homebrew/bin/upx 2>/dev/null || true)
    [[ -n "$UPX" ]] || { echo "ERROR: --upx given but upx not found (arm64: /opt/homebrew/bin/brew install upx)." >&2; exit 1; }
    echo "UPX:   $UPX"
fi

# The open editor rewrites export_presets.cfg from memory and can wipe the
# generated exclude list, so regenerate it right before exporting.
python3 "$PROJECT_DIR/tools/asset_audit/find_unused_assets.py" --write
echo ""

# ── Helpers ───────────────────────────────────────────────────────────────────

run_export() {
    local preset="$1"
    local out="$2"
    mkdir -p "$(dirname "$out")"
    "$GODOT" --headless --path "$PROJECT_DIR" --export-release "$preset" "$out"
}

# Compress an exported executable in place (no-op unless --upx).
upx_pack() {
    $USE_UPX || return 0
    local bin="$1"
    local before; before=$(stat -f%z "$bin")
    "$UPX" -q "$bin" >/dev/null
    "$UPX" -q -t "$bin" >/dev/null
    echo "    upx: $((before / 1048576)) MB -> $(( $(stat -f%z "$bin") / 1048576 )) MB  $(basename "$bin")"
}

zip_dir() {
    local src_dir="$1"
    local dest_zip="$2"
    (cd "$src_dir" && zip -r "$dest_zip" .)
}

xcodebuild_cmd() {
    DEVELOPER_DIR="$XCODE_DEVELOPER_DIR" \
        "$XCODE_DEVELOPER_DIR/usr/bin/xcodebuild" "$@"
}

xcrun_cmd() {
    DEVELOPER_DIR="$XCODE_DEVELOPER_DIR" \
        "$XCODE_DEVELOPER_DIR/usr/bin/xcrun" "$@"
}

# ── Platform builds ───────────────────────────────────────────────────────────

build_mac() {
    echo "==> macOS (universal)"
    local out="$BUILD_DIR/mac/$GAME_NAME.dmg"
    run_export "macOS" "$out"
    cp "$out" "$DIST_DIR/${GAME_NAME}-${VERSION}-mac.dmg"
    echo "    $DIST_DIR/${GAME_NAME}-${VERSION}-mac.dmg"
}

build_windows() {
    echo "==> Windows (x86_64)"
    local out="$BUILD_DIR/windows/$GAME_NAME.exe"
    run_export "Windows Desktop" "$out"
    upx_pack "$out"
    local zip="$DIST_DIR/${GAME_NAME}-${VERSION}-windows-x64.zip"
    zip_dir "$BUILD_DIR/windows" "$zip"
    echo "    $zip"
}

build_linux_x64() {
    echo "==> Linux (x86_64)"
    local out="$BUILD_DIR/linux/x86_64/$GAME_NAME.x86_64"
    run_export "Linux x86_64" "$out"
    chmod +x "$out"
    upx_pack "$out"
    local zip="$DIST_DIR/${GAME_NAME}-${VERSION}-linux-x64.zip"
    zip_dir "$BUILD_DIR/linux/x86_64" "$zip"
    echo "    $zip"
}

build_linux_arm64() {
    echo "==> Linux (arm64)"
    local out="$BUILD_DIR/linux/arm64/$GAME_NAME.arm64"
    run_export "Linux arm64" "$out"
    chmod +x "$out"
    upx_pack "$out"
    local zip="$DIST_DIR/${GAME_NAME}-${VERSION}-linux-arm64.zip"
    zip_dir "$BUILD_DIR/linux/arm64" "$zip"
    echo "    $zip"
}

build_ios() {
    echo "==> iOS (arm64)"

    if [[ -z "${IOS_TEAM_ID:-}" ]]; then
        echo "ERROR: IOS_TEAM_ID env var required for iOS build." >&2
        echo "  export IOS_TEAM_ID=XXXXXXXXXX" >&2
        exit 1
    fi

    if [[ ! -d "$XCODE_DEVELOPER_DIR" ]]; then
        echo "ERROR: Xcode not found at $XCODE_DEVELOPER_DIR" >&2
        exit 1
    fi

    local xcode_proj="$BUILD_DIR/ios/$GAME_NAME.xcodeproj"
    local archive="$BUILD_DIR/ios/$GAME_NAME.xcarchive"
    local export_dir="$BUILD_DIR/ios/export"
    local export_opts="$BUILD_DIR/ios/ExportOptions.plist"

    # 1. Export Xcode project via Godot
    mkdir -p "$BUILD_DIR/ios"
    run_export "iOS" "$xcode_proj"

    # 2. Archive
    echo "    Archiving…"
    xcodebuild_cmd archive \
        -project "$xcode_proj" \
        -scheme "$GAME_NAME" \
        -configuration Release \
        -archivePath "$archive" \
        -destination "generic/platform=iOS" \
        CODE_SIGN_STYLE=Automatic \
        DEVELOPMENT_TEAM="$IOS_TEAM_ID" \
        -quiet

    # 3. Write ExportOptions.plist
    cat > "$export_opts" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>method</key>
    <string>app-store</string>
    <key>teamID</key>
    <string>${IOS_TEAM_ID}</string>
    <key>signingStyle</key>
    <string>automatic</string>
    <key>uploadSymbols</key>
    <true/>
</dict>
</plist>
PLIST

    # 4. Export IPA
    echo "    Exporting IPA…"
    mkdir -p "$export_dir"
    xcodebuild_cmd -exportArchive \
        -archivePath "$archive" \
        -exportOptionsPlist "$export_opts" \
        -exportPath "$export_dir" \
        -quiet

    local ipa
    ipa=$(find "$export_dir" -name "*.ipa" | head -1)
    if [[ -z "$ipa" ]]; then
        echo "ERROR: IPA not found after export." >&2; exit 1
    fi

    cp "$ipa" "$DIST_DIR/${GAME_NAME}-${VERSION}-ios.ipa"
    echo "    $DIST_DIR/${GAME_NAME}-${VERSION}-ios.ipa"
}

upload_ios_to_asc() {
    local ipa="$DIST_DIR/${GAME_NAME}-${VERSION}-ios.ipa"
    [[ -f "$ipa" ]] || return 0

    echo ""
    echo "==> Uploading IPA to App Store Connect"

    if [[ -n "${ASC_API_KEY_ID:-}" && -n "${ASC_ISSUER_ID:-}" ]]; then
        xcrun_cmd altool --upload-app \
            -f "$ipa" -t ios \
            --apiKey "$ASC_API_KEY_ID" \
            --apiIssuer "$ASC_ISSUER_ID"
    elif [[ -n "${ASC_APPLE_ID:-}" && -n "${ASC_APP_PASSWORD:-}" ]]; then
        xcrun_cmd altool --upload-app \
            -f "$ipa" -t ios \
            -u "$ASC_APPLE_ID" \
            -p "$ASC_APP_PASSWORD"
    else
        echo "    Skipping App Store Connect upload — set one of:"
        echo "      ASC_API_KEY_ID + ASC_ISSUER_ID  (recommended)"
        echo "      ASC_APPLE_ID + ASC_APP_PASSWORD"
        echo "    IPA is ready at: $ipa"
    fi
}

# ── Google Drive upload ───────────────────────────────────────────────────────

upload_to_gdrive() {
    if ! command -v rclone &>/dev/null; then
        echo ""
        echo "WARNING: rclone not found — skipping Google Drive upload."
        echo "  Install: brew install rclone"
        echo "  Setup:   rclone config  (add a remote named '$GDRIVE_REMOTE')"
        return
    fi
    local remote_path="$GDRIVE_REMOTE:$GDRIVE_FOLDER/$VERSION"
    echo ""
    echo "==> Uploading to Google Drive: $remote_path"
    rclone copy "$DIST_DIR/" "$remote_path/" \
        --include "*${VERSION}*" \
        --progress \
        --stats-one-line
    echo "    https://drive.google.com (see '$GDRIVE_FOLDER/$VERSION' folder)"
}

# ── Main ──────────────────────────────────────────────────────────────────────

mkdir -p "$DIST_DIR"

should_build mac         && build_mac
should_build windows     && build_windows
should_build linux-x64   && build_linux_x64
should_build linux-arm64 && build_linux_arm64
should_build ios         && build_ios

if [[ "$SKIP_UPLOAD" == false ]]; then
    # Desktop builds → Google Drive
    upload_to_gdrive
    # iOS → App Store Connect (separate from Google Drive)
    should_build ios && upload_ios_to_asc
fi

if [[ -n "$STEAM_APP" ]]; then
    # Steam takes the raw .app / unzipped dirs, so it does its own exports.
    echo ""
    echo "==> Steam ($STEAM_APP)"
    GODOT="$GODOT" "$PROJECT_DIR/steam/steam_upload.sh" --app "$STEAM_APP" --desc "$STEAM_APP $VERSION"
fi

echo ""
echo "Done. Builds in: $DIST_DIR"
